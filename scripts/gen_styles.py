#!/usr/bin/env python3
"""Generate every backend's style file from tokens.yaml.

    python scripts/gen_styles.py            # regenerate in place
    python scripts/gen_styles.py --check    # exit 1 if anything is stale

Outputs:
    backends/tikz/mlfig.sty
    backends/svg/mlfig.css            (also injected into every SVG template
                                       between the mlfig:begin/end markers)
    backends/mpl/mlfig.mplstyle
    backends/mpl/mlfig_tokens.json    (read by backends/mpl/mlfig.py)
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover
    sys.exit("PyYAML is required: pip install pyyaml")

ROOT = Path(__file__).resolve().parent.parent
PT2PX = 96 / 72
HEADER = "Generated by scripts/gen_styles.py from tokens.yaml - do not edit by hand."


# ---------------------------------------------------------------- colour math
def _rgb(hex_: str) -> tuple[int, int, int]:
    h = hex_.lstrip("#")
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def _hex(rgb) -> str:
    return "#" + "".join(f"{round(c):02X}" for c in rgb)


def mix(hex_: str, pct: float, other: str = "#FFFFFF") -> str:
    """xcolor `hue!pct!other`: pct% of hue, rest of `other` (white by default)."""
    a, b = _rgb(hex_), _rgb(other)
    p = pct / 100
    return _hex(tuple(p * x + (1 - p) * y for x, y in zip(a, b)))


def load_tokens() -> dict:
    t = yaml.safe_load((ROOT / "tokens.yaml").read_text(encoding="utf-8"))
    # Flatten semantic groups into name -> palette hue.
    sem = {}
    for group in t["semantic"].values():
        for name, hue in group.items():
            if hue not in t["palette"]:
                sys.exit(f"tokens.yaml: semantic '{name}' uses unknown hue '{hue}'")
            if name in sem or name in t["palette"]:
                sys.exit(f"tokens.yaml: duplicate colour name '{name}'")
            sem[name] = hue
    t["_sem"] = sem
    return t


def all_colours(t) -> dict[str, str]:
    """Every usable colour name (palette + semantic) -> base hex."""
    out = dict(t["palette"])
    out.update({k: t["palette"][v] for k, v in t["_sem"].items()})
    return out


# ---------------------------------------------------------------------- TikZ
def gen_sty(t) -> str:
    p, tint, shade, st, ds = t["palette"], t["tint"], t["shade"], t["stroke"], t["dash"]
    L = [f"% {HEADER}",
         "\\NeedsTeXFormat{LaTeX2e}",
         "\\ProvidesPackage{mlfig}[ML figure style]",
         "\\RequirePackage{xcolor}",
         "\\RequirePackage{tikz}",
         "\\usetikzlibrary{arrows.meta,positioning,calc,fit,backgrounds,matrix,shapes.geometric,decorations.pathreplacing}",
         "",
         "% ---- palette (use as ml<name>, e.g. mlblue!15)"]
    for k, v in p.items():
        L.append(f"\\definecolor{{ml{k}}}{{HTML}}{{{v.lstrip('#')}}}")
    L.append("")
    L.append("% ---- semantic colours (concept -> hue), e.g. mlattention")
    for k, v in t["_sem"].items():
        L.append(f"\\colorlet{{ml{k}}}{{ml{v}}}")
    a = t["arrow"]
    L += ["",
          "% ---- styles. Apply `ml` to the picture: \\begin{tikzpicture}[ml]",
          "\\tikzset{",
          f"  ml/.style={{font=\\footnotesize, line join=round, line width={st['thin']}pt,",
          "    >={Latex[length=%spt,width=%spt]}," % (a["length"], a["width"]),
          "    every node/.append style={inner sep=0pt, outer sep=0pt, align=center}},",
          "  w/.style={minimum width=#1}, h/.style={minimum height=#1}, s/.style={minimum size=#1},",
          f"  block/.style={{draw=mlink, line width={st['thin']}pt, fill=ml#1!{tint['block']},",
          f"    rounded corners={t['radius']['block']}pt, minimum width=2cm, minimum height=.8cm}},",
          "  block/.default=gray,",
          "  op/.style={block=#1},   % op=attention, op=norm, op=mlp ...",
          f"  thinblock/.style={{block=#1, minimum height=.4cm}},",
          f"  region/.style={{draw=mlink, densely dotted, fill=ml#1!{tint['region']}}},",
          "  group/.style={draw=mlink, densely dashed, fill=none},",
          f"  neuron/.style={{circle, line width={st['thick']}pt, draw=ml#1!{shade['outline']}!black,",
          f"    fill=ml#1!{tint['node']}, text=ml#1!{shade['outline']}!black, minimum size=22pt}},",
          "  neuron/.default=hidden,",
          f"  edge/.style={{line width={st['thick']}pt, draw=mlnavy}},",
          "  halo/.style={draw=white, line width=1.2pt},  % draw under crossing edges",
          f"  cell/.style={{draw=mlink!70, line width={st['hairline']}pt, fill=ml#1!{tint['node']}}},",
          f"  hot/.style={{fill=ml#1!{tint['emphasis']}}},",
          f"  tag/.style={{text=ml#1!{shade['label']}!black}},  % coloured label text",
          "  title/.style={font=\\footnotesize\\bfseries},",
          "  note/.style={font=\\scriptsize},",
          "  sum/.style={circle, draw=mlink, minimum size=.3cm, font=\\scriptsize},",
          "}",
          "",
          "% \\tensorgrid[<draw options>]{<node>}: grid lines inside a rectangular node,",
          "% aligned to the node's corner. Cell size via `step=`, default .25cm.",
          "\\newcommand{\\tensorgrid}[2][]{%",
          "  \\path let \\p1=($(#2.north east)-(#2.south west)$) in",
          "    \\pgfextra{\\xdef\\mlgw{\\x1}\\xdef\\mlgh{\\y1}};",
          "  \\begin{scope}[shift={(#2.south west)}]",
          "    \\draw[step=.25cm, line width=%spt, mlink!70, #1] (0,0) grid (\\mlgw-.01pt,\\mlgh-.01pt);" % st["hairline"],
          "  \\end{scope}}",
          "\\endinput",
          ""]
    return "\n".join(L)


# ----------------------------------------------------------------------- SVG
def gen_css(t) -> str:
    tint, shade, st, ds, f = t["tint"], t["shade"], t["stroke"], t["dash"], t["font"]
    px = lambda v: f"{round(v * PT2PX, 2)}px"
    k = st.get("svg_scale", 1)
    st = {n: v * k for n, v in st.items() if n != "svg_scale"}
    dash = lambda s: " ".join(str(round(float(x) * PT2PX * k, 2)) for x in s.split())
    serif = ", ".join(f"'{x}'" if " " in x else x for x in f["serif"])
    mono = ", ".join(f"'{x}'" if " " in x else x for x in f["mono"])
    ink = t["palette"]["ink"]
    L = [f"/* {HEADER} */",
         f"svg {{ background: {t['palette']['paper']}; }}",
         f"text {{ font-family: {serif}; font-size: {px(f['size']['label'])}; fill: {ink};"
         " text-anchor: middle; dominant-baseline: central; }",
         f".small {{ font-size: {px(f['size']['small'])}; }}",
         f".title {{ font-size: {px(f['size']['title'])}; font-weight: bold; }}",
         f".mono {{ font-family: {mono}; }}",
         ".start { text-anchor: start; } .end { text-anchor: end; }",
         ".math { font-style: italic; }",
         f".blk {{ stroke: {ink}; stroke-width: {px(st['thin'])}; }}",
         f".line {{ fill: none; stroke: {ink}; stroke-width: {px(st['thin'])}; stroke-linejoin: round; }}",
         f".edge {{ fill: none; stroke: {t['palette']['navy']}; stroke-width: {px(st['thick'])}; }}",
         f".halo {{ fill: none; stroke: #FFFFFF; stroke-width: {px(st['thick'] + 1.2)}; }}",
         f".neuron {{ stroke-width: {px(st['thick'])}; }}",
         f".cell {{ stroke: {mix(ink, 70)}; stroke-width: {px(st['hairline'])}; }}",
         f".grid {{ fill: none; stroke: {mix(ink, 70)}; stroke-width: {px(st['hairline'])}; }}",
         f".region {{ stroke: {ink}; stroke-width: {px(st['thin'])}; stroke-dasharray: {dash(ds['dotted'])}; }}",
         f".group {{ fill: none; stroke: {ink}; stroke-width: {px(st['thin'])}; stroke-dasharray: {dash(ds['dashed'])}; }}",
         f".dashed {{ stroke-dasharray: {dash(ds['dashed'])}; }}",
         f".dotted {{ stroke-dasharray: {dash(ds['dotted'])}; }}",
         ".arrow { marker-end: url(#ml-arrow); }",
         ".arrow2 { marker-start: url(#ml-arrow-rev); marker-end: url(#ml-arrow); }",
         ".arrow-navy { marker-end: url(#ml-arrow-navy); }",
         "/* colour classes, for any palette or semantic NAME: f-NAME block fill,",
         "   fn-NAME node fill, fr-NAME region fill, fe-NAME emphasis fill,",
         "   s-NAME outline stroke (hue!30!black), t-NAME label text (hue!60!black),",
         "   c-NAME solid fill, k-NAME solid stroke, kl-NAME light stroke (hue!70) */"]
    for name, hx in all_colours(t).items():
        L.append(f".f-{name} {{ fill: {mix(hx, tint['block'])}; }} "
                 f".fn-{name} {{ fill: {mix(hx, tint['node'])}; }} "
                 f".fr-{name} {{ fill: {mix(hx, tint['region'])}; }} "
                 f".fe-{name} {{ fill: {mix(hx, tint['emphasis'])}; }} "
                 f".s-{name} {{ stroke: {mix(hx, shade['outline'], '#000000')}; }} "
                 f".t-{name} {{ fill: {mix(hx, shade['label'], '#000000')}; }} "
                 f".c-{name} {{ fill: {hx}; }} "
                 f".k-{name} {{ stroke: {hx}; }} "
                 f".kl-{name} {{ stroke: {mix(hx, 70)}; }}")
    return "\n".join(L) + "\n"


def svg_defs(t) -> str:
    """Arrow-head markers, Latex-shaped. Sized in user units (px)."""
    a = t["arrow"]
    l, w = round(a["length"] * PT2PX, 2), round(a["width"] * PT2PX, 2)
    path = f"M0,0 L{l},{w/2} L0,{w} Q{l*0.25},{w/2} 0,0 Z"
    def marker(id_, colour, orient="auto"):
        return (f'<marker id="{id_}" viewBox="0 0 {l} {w}" refX="{l}" refY="{w/2}" '
                f'markerUnits="userSpaceOnUse" markerWidth="{l}" markerHeight="{w}" orient="{orient}">'
                f'<path d="{path}" fill="{colour}"/></marker>')
    return ("<defs>"
            + marker("ml-arrow", t["palette"]["ink"])
            + marker("ml-arrow-rev", t["palette"]["ink"], "auto-start-reverse")
            + marker("ml-arrow-navy", t["palette"]["navy"])
            + "</defs>")


BLOCK_RE = re.compile(r"(<!-- mlfig:begin -->).*?(<!-- mlfig:end -->)", re.S)


def inject_svg(template: str, css: str, defs: str) -> str:
    body = f"\\1\n<style><![CDATA[\n{css}]]></style>\n{defs}\n\\2"
    if not BLOCK_RE.search(template):
        raise ValueError("missing <!-- mlfig:begin --> / <!-- mlfig:end --> markers")
    return BLOCK_RE.sub(lambda m: body.replace("\\1", m.group(1)).replace("\\2", m.group(2)), template)


# ---------------------------------------------------------------- matplotlib
def gen_mplstyle(t) -> str:
    p, st, f = t["palette"], t["stroke"], t["font"]
    cycle = ["blue2", "red", "green", "orange", "purple", "cyan", "gray"]
    cyc = ", ".join(f"'{p[c].lstrip('#')}'" for c in cycle)
    serif = ", ".join(x for x in f["serif"] if x != "serif")
    return "\n".join([
        f"# {HEADER}",
        "font.family: serif",
        f"font.serif: {serif}",
        "mathtext.fontset: cm",
        "axes.formatter.use_mathtext: True",
        f"font.size: {f['size']['label']}",
        f"axes.labelsize: {f['size']['label']}",
        f"axes.titlesize: {f['size']['title']}",
        "axes.titleweight: bold",
        f"xtick.labelsize: {f['size']['small']}",
        f"ytick.labelsize: {f['size']['small']}",
        f"legend.fontsize: {f['size']['small']}",
        f"axes.prop_cycle: cycler('color', [{cyc}])",
        f"axes.edgecolor: {p['ink'].lstrip('#')}",
        f"axes.labelcolor: {p['ink'].lstrip('#')}",
        f"axes.linewidth: {st['heavy']}",
        "axes.spines.top: False",
        "axes.spines.right: False",
        "axes.grid: False",
        f"grid.color: {mix(p['gray'], 35).lstrip('#')}",
        f"grid.linewidth: {st['hairline']}",
        "xtick.major.size: 0",
        "ytick.major.size: 0",
        "xtick.major.pad: 3",
        "ytick.major.pad: 3",
        f"lines.linewidth: {st['curve']}",
        "lines.solid_capstyle: round",
        "lines.dash_capstyle: round",
        f"patch.linewidth: {st['thin']}",
        "legend.frameon: True",
        "legend.fancybox: False",
        "legend.framealpha: 1",
        f"legend.edgecolor: {p['ink'].lstrip('#')}",
        "legend.borderpad: 0.4",
        "legend.handlelength: 2.2",
        "figure.figsize: 4.0, 2.8",
        "figure.dpi: 150",
        "savefig.dpi: 300",
        "savefig.bbox: tight",
        "savefig.pad_inches: 0.03",
        f"figure.facecolor: {p['paper'].lstrip('#')}",
        f"axes.facecolor: {p['paper'].lstrip('#')}",
        "svg.fonttype: none",
        "pdf.fonttype: 42",
        "image.cmap: mlfig_seq",
        ""])


def gen_tokens_json(t) -> str:
    cols = all_colours(t)
    return json.dumps({
        "_comment": HEADER,
        "palette": t["palette"],
        "semantic": t["_sem"],
        "tint": t["tint"], "shade": t["shade"], "stroke": t["stroke"],
        "fills": {k: {"block": mix(v, t["tint"]["block"]), "node": mix(v, t["tint"]["node"]),
                      "region": mix(v, t["tint"]["region"]), "emphasis": mix(v, t["tint"]["emphasis"]),
                      "outline": mix(v, t["shade"]["outline"], "#000000"),
                      "label": mix(v, t["shade"]["label"], "#000000")} for k, v in cols.items()},
    }, indent=1) + "\n"


# ---------------------------------------------------------------------- main
def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="only report stale files")
    args = ap.parse_args()
    t = load_tokens()
    css, defs = gen_css(t), svg_defs(t)
    targets = {
        ROOT / "backends/tikz/mlfig.sty": gen_sty(t),
        ROOT / "backends/svg/mlfig.css": css,
        ROOT / "backends/svg/defs.svg": defs + "\n",
        ROOT / "backends/mpl/mlfig.mplstyle": gen_mplstyle(t),
        ROOT / "backends/mpl/mlfig_tokens.json": gen_tokens_json(t),
    }
    for svg in sorted((ROOT / "backends/svg/templates").glob("*.svg")):
        targets[svg] = inject_svg(svg.read_text(encoding="utf-8"), css, defs)

    stale = []
    for path, content in targets.items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != content:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")
    for s in stale:
        print(("stale: " if args.check else "wrote: ") + str(s.relative_to(ROOT)))
    return 1 if (args.check and stale) else 0


if __name__ == "__main__":
    sys.exit(main())
